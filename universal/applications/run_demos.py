"""Run every application demo and write results/universal/applications.{json,md}."""
from __future__ import annotations

import json
from pathlib import Path

from . import air_traffic, drones, energy_mixed, epidemics, grid, logistics, wildfire

OUT = Path(__file__).resolve().parents[2] / "results" / "universal"


def main() -> None:
    res = {}
    for name, mod in [("grid", grid), ("energy_mixed_roles", energy_mixed), ("wildfire", wildfire), ("epidemics", epidemics),
                      ("air_traffic", air_traffic), ("drones", drones), ("logistics", logistics)]:
        try:
            res[name] = mod.demo()
        except Exception as e:
            res[name] = {"error": repr(e)}
        print(name, json.dumps(res[name], default=float)[:300], flush=True)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "applications.json").write_text(json.dumps(res, indent=1, default=float))
    lines = ["# Application frameworks: demo results", "",
             "Generated by `python -m universal.applications.run_demos`. Entries marked "
             "'simulated (not evidence)' are simulations that show the framework runs; the others use real data.", ""]
    for k, v in res.items():
        lines += [f"## {k}", "", "```json", json.dumps(v, indent=1, default=float), "```", ""]
    (OUT / "applications.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
