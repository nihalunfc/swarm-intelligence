"""Cross-dataset ensemble: which characteristics do all real swarms share?

* PCA on the standardised feature table gives the main axes of variation ("major characteristics").
* Hierarchical clustering groups datasets that behave alike, whatever their domain.
* The general-equation constants are summarised by their median and spread across datasets,
  and re-estimated leaving one domain group out at a time (a stability check, not a proof).
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.cluster.hierarchy import fcluster, linkage

CONSTANTS = {
    "dr_a1": "linear restoring coefficient a1 (negative = self-regulating)",
    "dr_taylor_gamma": "fluctuation scaling exponent gamma (0.5 independent, 1 collective)",
    "gr_theta": "Richards shape theta of growth curves (1 = logistic)",
    "ev_tail_alpha": "power-law tail exponent of event sizes",
    "se_dfa_increments": "DFA exponent of increments (<0.5 anti-persistent, >0.5 persistent)",
    "tr_alpha_align": "alignment gain alpha (dimensionless)",
    "tr_beta_cohesion": "cohesion gain beta (dimensionless)",
    "tr_gamma_speed": "speed set-point gain (dimensionless)",
    "tr_switch_r_over_dnn": "repulsion-to-attraction switch distance / nearest-neighbour distance",
    "tr_polarization": "polarization (order)",
}


def analyse(table: pd.DataFrame) -> dict:
    num = table.drop(columns=["key", "group"]).apply(pd.to_numeric, errors="coerce")
    out = {"n_datasets": int(len(table))}
    # ---- constants of the general equation
    const = {}
    for c, desc in CONSTANTS.items():
        if c not in num:
            continue
        v = num[c].dropna()
        if len(v) == 0:
            continue
        loo = {}
        for g in table["group"].unique():
            w = num.loc[table["group"] != g, c].dropna()
            if len(w):
                loo[g] = float(w.median())
        const[c] = {"desc": desc, "n": int(len(v)), "median": float(v.median()),
                    "q25": float(v.quantile(0.25)), "q75": float(v.quantile(0.75)),
                    "min": float(v.min()), "max": float(v.max()),
                    "leave_one_group_out_range": [min(loo.values()), max(loo.values())] if loo else None,
                    "by_dataset": {k: float(x) for k, x in zip(table.loc[v.index, "key"], v)}}
    out["constants"] = const
    # ---- universality checks
    checks = {}
    if "dr_a1" in num:
        a1 = num["dr_a1"].dropna()
        checks["self_regulating_share"] = {"value": float((a1 < 0).mean()), "n": int(len(a1)),
                                           "desc": "share of datasets whose collective level is pulled back (a1<0)"}
    if "ev_tail_alpha" in num:
        a = num["ev_tail_alpha"].dropna()
        checks["heavy_tail_share"] = {"value": float(((a > 1) & (a < 3)).mean()), "n": int(len(a)),
                                      "desc": "share of event-size distributions with tail exponent between 1 and 3"}
    if "se_dfa_increments" in num:
        d = num["se_dfa_increments"].dropna()
        checks["antipersistent_share"] = {"value": float((d < 0.5).mean()), "n": int(len(d)),
                                          "desc": "share of datasets whose changes reverse more than chance (DFA<0.5)"}
    if "tr_alpha_align" in num:
        al = num["tr_alpha_align"].dropna()
        checks["alignment_positive_share"] = {"value": float((al > 0).mean()), "n": int(len(al)),
                                              "desc": "share of moving swarms where agents turn toward neighbours' heading"}
    out["checks"] = checks
    # ---- PCA on features present for at least 40% of datasets
    keep = [c for c in num if num[c].notna().mean() >= 0.4]
    X = num[keep].copy()
    X = X.fillna(X.median())
    Z = (X - X.mean()) / X.std(ddof=0).replace(0, 1)
    U, S, Vt = np.linalg.svd(Z.to_numpy(), full_matrices=False)
    var = S**2 / np.sum(S**2)
    out["pca"] = {
        "features": keep,
        "explained": [float(v) for v in var[:4]],
        "loadings": {f"PC{i + 1}": {f: float(w) for f, w in sorted(zip(keep, Vt[i]), key=lambda x: -abs(x[1]))[:6]}
                     for i in range(min(3, len(var)))},
        "scores": {k: [float(a) for a in row[:3]] for k, row in zip(table["key"], U * S)},
    }
    L = linkage(Z.to_numpy(), "ward")
    cl = fcluster(L, t=4, criterion="maxclust")
    out["clusters"] = {}
    for k, c in zip(table["key"], cl):
        out["clusters"].setdefault(f"C{c}", []).append(k)
    return out


def _fmt(x, nd=3):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "-"
    return f"{x:.{nd}g}" if isinstance(x, float) else str(x)


def report(rows: list[dict], table: pd.DataFrame, ens: dict, out: Path) -> None:
    L = ["# Universal swarm study: results", "",
         "Generated by `python -m universal.run_study`. Real recorded data only; see "
         "[sources](../../universal/sources.yaml). Numbers are point estimates on one pass of the data; "
         "treat small differences as noise.", "",
         "## Datasets", "", "| Key | Category | Group | Status |", "| :-- | :-- | :-- | :-- |"]
    for r in rows:
        L.append(f"| {r['key']} | {r.get('category', '')} | {r.get('group', '')} | "
                 f"{'failed: ' + r['error'][:60] if 'error' in r else 'ok'} |")
    L += ["", "Cosmic datasets (SPARC, Pantheon+, DESI DR2 BAO, cosmic chronometers) are analysed in "
          "[cosmology.md](cosmology.md).", "",
          "## Agent-level rule (moving swarms)", "",
          "a = alpha (neighbour velocity - own) + beta (neighbour centre - own) + gamma (v0 - |v|) v_hat, "
          "lengths in nearest-neighbour distances, speeds in the typical speed.", "",
          "| Swarm | Polarization | alpha (align) | beta (cohesion) | gamma (speed set-point) | R2 | switch r/d_nn |",
          "| :-- | --: | --: | --: | --: | --: | --: |"]
    for r in rows:
        t = r.get("tracks")
        if not t:
            continue
        L.append(f"| {r['key']} | {_fmt(t.get('polarization'))} | {_fmt(t.get('alpha_align'))} ± {_fmt(t.get('alpha_se'), 2)} "
                 f"| {_fmt(t.get('beta_cohesion'))} | {_fmt(t.get('gamma_speed'))} | {_fmt(t.get('rule_r2'), 2)} "
                 f"| {_fmt(t.get('switch_r_over_dnn'))} |")
    L += ["", "## Collective level (series)", "",
          "| Dataset | a1 (restoring) | Taylor gamma | DFA of changes | spectral slope | growth model (Richards theta) |",
          "| :-- | --: | --: | --: | --: | :-- |"]
    for r in rows:
        if "series" not in r:
            continue
        dr, s, g = r.get("drift", {}), r.get("series", {}), r.get("growth", {})
        gm = ""
        if g:
            gm = ", ".join(f"{k} {v}" for k, v in g.get("best_model_counts", {}).items()) + f" (theta {_fmt(g.get('theta'))})"
        L.append(f"| {r['key']} | {_fmt(dr.get('a1'))} | {_fmt(dr.get('taylor_gamma'))} | {_fmt(s.get('dfa_increments'))} "
                 f"| {_fmt(s.get('spectral_slope'))} | {gm} |")
    L += ["", "## Event sizes", "", "| Dataset | Events | n | tail alpha | tail starts at quantile | LR vs lognormal (p) |",
          "| :-- | :-- | --: | --: | --: | --: |"]
    for r in rows:
        for e in r.get("events", []):
            L.append(f"| {r['key']} | {e['label']} | {e['n']} | {_fmt(e.get('tail_alpha'))} | {_fmt(e.get('tail_xmin_quantile'), 2)} "
                     f"| {_fmt(e.get('pl_vs_lognormal_LR'))} ({_fmt(e.get('pl_vs_lognormal_p'), 2)}) |")
    L += ["", "## Ensemble: constants of the general equation", "",
          "| Constant | n | median | IQR | leave-one-group-out median range |", "| :-- | --: | --: | :-- | :-- |"]
    for c, v in ens["constants"].items():
        lo = v["leave_one_group_out_range"]
        L.append(f"| {v['desc']} | {v['n']} | {_fmt(v['median'])} | {_fmt(v['q25'])} to {_fmt(v['q75'])} | "
                 f"{_fmt(lo[0]) + ' to ' + _fmt(lo[1]) if lo else '-'} |")
    L += ["", "## Universality checks", ""]
    for k, v in ens["checks"].items():
        L.append(f"- **{v['desc']}**: {v['value']:.0%} of {v['n']}")
    L += ["", "## Major characteristics (PCA)", ""]
    for i, (pc, ld) in enumerate(ens["pca"]["loadings"].items()):
        L.append(f"- **{pc}** ({ens['pca']['explained'][i]:.0%} of variance): "
                 + ", ".join(f"{k} {w:+.2f}" for k, w in ld.items()))
    L += ["", "Clusters (Ward, 4 groups): " + "; ".join(f"{c}: {', '.join(v)}" for c, v in ens["clusters"].items()), ""]
    (out / "REPORT.md").write_text("\n".join(L))
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        fig, ax = plt.subplots(figsize=(7, 5))
        groups = sorted(table["group"].unique())
        for gi, g in enumerate(groups):
            ks = table.loc[table["group"] == g, "key"]
            xy = np.array([ens["pca"]["scores"][k][:2] for k in ks])
            ax.scatter(xy[:, 0], xy[:, 1], label=g, s=40)
            for k, (x, y) in zip(ks, xy):
                ax.annotate(k, (x, y), fontsize=7, xytext=(3, 3), textcoords="offset points")
        ax.set_xlabel(f"PC1 ({ens['pca']['explained'][0]:.0%})")
        ax.set_ylabel(f"PC2 ({ens['pca']['explained'][1]:.0%})")
        ax.legend(fontsize=7, frameon=False)
        ax.set_title("Real swarms in feature space")
        fig.tight_layout()
        fig.savefig(out / "pca.png", dpi=130)
    except Exception as e:  # plotting is optional
        (out / "plot_error.txt").write_text(repr(e))
    json.dumps(ens, default=float)
